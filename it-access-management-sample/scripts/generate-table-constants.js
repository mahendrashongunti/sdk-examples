#!/usr/bin/env node

/**
 * Auto-generate table and column constants from table definition files
 * This script parses .now.ts table files and generates TypeScript constants
 * 
 * Usage: node scripts/generate-table-constants.js
 */

const fs = require('fs');
const path = require('path');

// Configuration
const TABLES_DIR = path.join(__dirname, '../src/fluent/tables');
const OUTPUT_DIR = path.join(__dirname, '../src/fluent/constants');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'tables.ts');

/**
 * Parse a table definition file to extract table name and columns
 */
function parseTableFile(filePath) {
    const content = fs.readFileSync(filePath, 'utf-8');
    
    // Extract table name from Table({ name: '...' })
    const tableNameMatch = content.match(/name:\s*['"]([^'"]+)['"]/);
    if (!tableNameMatch) {
        console.warn(`Could not find table name in ${filePath}`);
        return null;
    }
    
    const tableName = tableNameMatch[1];
    
    // Extract schema section - need to match nested braces properly
    const schemaStart = content.indexOf('schema: {');
    if (schemaStart === -1) {
        console.warn(`Could not find schema in ${filePath}`);
        return { tableName, columns: [] };
    }
    
    // Find matching closing brace for schema
    let braceCount = 0;
    let schemaEnd = schemaStart + 8; // Skip 'schema: {'
    let inString = false;
    let stringChar = null;
    
    for (let i = schemaStart + 8; i < content.length; i++) {
        const char = content[i];
        const prevChar = i > 0 ? content[i - 1] : '';
        
        // Handle strings
        if ((char === '"' || char === "'" || char === '`') && prevChar !== '\\') {
            if (!inString) {
                inString = true;
                stringChar = char;
            } else if (char === stringChar) {
                inString = false;
                stringChar = null;
            }
        }
        
        if (!inString) {
            if (char === '{') braceCount++;
            if (char === '}') {
                if (braceCount === 0) {
                    schemaEnd = i;
                    break;
                }
                braceCount--;
            }
        }
    }
    
    const schemaContent = content.substring(schemaStart + 9, schemaEnd);
    
    // Extract column names - match property names before Column definitions
    const columnRegex = /^\s*(\w+):\s*(?:String|DateTime|Reference|Integer|Boolean|Text)Column\s*\(/gm;
    const columns = [];
    let match;
    
    while ((match = columnRegex.exec(schemaContent)) !== null) {
        columns.push(match[1]);
    }
    
    return {
        tableName,
        columns: columns
    };
}

/**
 * Convert snake_case to SCREAMING_SNAKE_CASE for enum keys
 */
function toEnumKey(str) {
    return str.toUpperCase();
}

/**
 * Convert table name to a proper enum key (remove prefix, convert to SCREAMING_SNAKE_CASE)
 */
function tableNameToEnumKey(tableName) {
    // Remove x_itaccess_ prefix and convert to SCREAMING_SNAKE_CASE
    const withoutPrefix = tableName.replace(/^x_itaccess_/, '');
    return toEnumKey(withoutPrefix);
}

/**
 * Generate TypeScript enum and constants
 */
function generateConstants(tables) {
    const timestamp = new Date().toISOString();
    
    let output = `/**
 * Auto-generated table and column constants
 * Generated on: ${timestamp}
 * 
 * DO NOT EDIT THIS FILE MANUALLY
 * Run 'npm run generate:constants' to regenerate
 */

/**
 * Table names enum for type-safe table references
 */
export enum TableNames {
`;

    // Generate TableNames enum
    tables.forEach(table => {
        const enumKey = tableNameToEnumKey(table.tableName);
        output += `    ${enumKey} = '${table.tableName}',\n`;
    });
    
    output += `}\n\n`;
    
    // Generate TableColumns object
    output += `/**
 * Column names for each table
 * Use with TableColumns[TableNames.ACCESS_REQUEST].REQUESTED_BY
 */
export const TableColumns = {\n`;
    
    tables.forEach(table => {
        const enumKey = tableNameToEnumKey(table.tableName);
        output += `    ${enumKey}: {\n`;
        
        table.columns.forEach(column => {
            const columnKey = toEnumKey(column);
            output += `        ${columnKey}: '${column}',\n`;
        });
        
        output += `    },\n`;
    });
    
    output += `} as const;\n\n`;
    
    // Add type exports
    output += `/**
 * Type helper for table column names
 */
export type TableColumnNames<T extends TableNames> = keyof typeof TableColumns[T];\n\n`;
    
    output += `/**
 * Type helper to get column name string from table
 */
export type ColumnValue<T extends TableNames, C extends TableColumnNames<T>> = typeof TableColumns[T][C];\n`;
    
    return output;
}

/**
 * Main execution
 */
function main() {
    console.log('🔍 Scanning table definition files...');
    
    // Read all .now.ts files from tables directory
    const files = fs.readdirSync(TABLES_DIR)
        .filter(file => file.endsWith('.now.ts'))
        .map(file => path.join(TABLES_DIR, file));
    
    console.log(`📁 Found ${files.length} table definition files`);
    
    // Parse each file
    const tables = [];
    files.forEach(file => {
        console.log(`   Parsing: ${path.basename(file)}`);
        const tableInfo = parseTableFile(file);
        if (tableInfo) {
            tables.push(tableInfo);
            console.log(`   ✓ ${tableInfo.tableName} (${tableInfo.columns.length} columns)`);
        }
    });
    
    // Generate constants
    console.log('\n📝 Generating constants...');
    const constants = generateConstants(tables);
    
    // Ensure output directory exists
    if (!fs.existsSync(OUTPUT_DIR)) {
        fs.mkdirSync(OUTPUT_DIR, { recursive: true });
        console.log(`   Created directory: ${OUTPUT_DIR}`);
    }
    
    // Write output file
    fs.writeFileSync(OUTPUT_FILE, constants, 'utf-8');
    console.log(`\n✅ Generated: ${OUTPUT_FILE}`);
    console.log(`   ${tables.length} tables`);
    console.log(`   ${tables.reduce((sum, t) => sum + t.columns.length, 0)} total columns`);
    
    // Print usage example
    console.log('\n📚 Usage example:');
    console.log(`   import { TableNames, TableColumns } from './constants/tables';`);
    console.log(`   `);
    console.log(`   const gr = new GlideRecord(TableNames.ACCESS_REQUEST);`);
    console.log(`   gr.addQuery(TableColumns.ACCESS_REQUEST.STATE, 'pending_approval');`);
}

// Run the script
try {
    main();
} catch (error) {
    console.error('❌ Error:', error.message);
    process.exit(1);
}
